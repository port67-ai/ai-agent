import assert from "node:assert/strict";
import { createProject, transition, projectView, strategyHash } from "../src/lib/factory/engine";
import { planProject, syncTaskPlan, selectedResearch, validateTaskGraph, taskResearchCurrent, requirePlannedTask } from "../src/lib/factory/task-plan";
import type { Principal, ResearchRun } from "../src/lib/factory/model";

import { templateScope } from "../src/lib/factory/scope";
import { planNext, registerResearchRunner } from "../src/lib/factory/producer-agent";

const op: Principal = { workspaceId: "w", subject: "producer", role: "operator" };
const make = (objective: string, workRequest = "campaign") => createProject({ business: "Shop", objective, contact: "a@example.com", workRequest }, op, "p");
const p = make("Create a written blog about our services");
assert.ok(p.taskPlan, "new projects have a persisted plan");
assert.ok(!selectedResearch(p).includes("video"));
assert.ok(!selectedResearch(p).includes("trends"));
assert.ok(!selectedResearch(p).includes("adjacent"));
assert.ok(selectedResearch(p).includes("brand"));
assert.ok(p.taskPlan!.tasks.find(t => t.id === "research:video")?.reason);
assert.throws(() => requirePlannedTask(p, "research:video"), /excluded|selected/i);
assert.throws(() => requirePlannedTask(p, "draftDirection"), /dependenc/i);
const v = make("Create a video advert for YouTube and TikTok");
assert.ok(selectedResearch(v).includes("video"));
assert.ok(selectedResearch(v).includes("trends"));
const staticOnly = createProject({ business: "Video production agency", objective: "Create static ads, no video", description: "We produce video", contact: "a@example.com", workRequest: "campaign", requestedFormats: ["static"] }, op);
assert.ok(!selectedResearch(staticOnly).includes("video"), "explicit outputs take precedence over industry words and negated requests");
assert.throws(() => createProject({ business: "Shop", objective: "Launch", contact: "a@example.com", requestedFormats: ["unknown"] }, op), /format/i);
const r = make("Understand customer objections", "research");
assert.ok(!r.taskPlan!.tasks.some(t => t.id === "draftDirection"));
assert.ok(!selectedResearch(r).includes("creative"));
assert.ok(r.taskPlan!.tasks.some(t => t.id === "reviewInsights"));
assert.throws(() => validateTaskGraph([{ id: "a", dependsOn: ["b"] }, { id: "b", dependsOn: ["a"] }]), /cycle/i);
assert.throws(() => validateTaskGraph([{ id: "a", dependsOn: ["missing"] }]), /dependency/i);

const before = p.taskPlan!.version;
planProject(p, op.subject, "unchanged");
assert.equal(p.taskPlan!.version, before, "reconciliation is idempotent");
const changed = transition(p, { type: "reviseTaskPlan", research: ["brand", "customer", "video"], reason: "Producer requests reference video research", version: before }, op);
assert.ok(selectedResearch(changed).includes("video"));
assert.equal(changed.taskPlan!.version, before + 1);
assert.equal(changed.taskPlan!.history.length, 1);
assert.ok(changed.audit.some(a => a.action === "task_plan_revised"));
assert.throws(() => transition(changed, { type: "reviseTaskPlan", research: ["unknown"], reason: "test", version: before + 1 }, op), /research/i);
assert.throws(() => transition(changed, { type: "reviseTaskPlan", research: ["brand"], reason: "test", version: before }, op), /changed|refresh/i);
assert.throws(() => transition(changed, { type: "reviseTaskPlan", research: ["brand"], reason: "test", version: before + 1 }, { ...op, role: "customer", identity: "firebase", accountId: "w" }), /operator/i);

const run = { id: "run1", stage: "research", segment: "brand", at: new Date().toISOString(), finishedAt: new Date().toISOString(), status: "completed", provider: "test", model: "test", taskInputKey: changed.taskPlan!.researchKey } as ResearchRun;
changed.runs.push(run);
changed.scope = templateScope(changed, { briefHash: "test", version: 1 });
syncTaskPlan(changed);
assert.equal(changed.taskPlan!.tasks.find(t => t.id === "research:brand")!.status, "done");
assert.ok(taskResearchCurrent(changed, run));
const updated = transition(changed, { type: "updateBrief", objective: "Research customers for a completely different product" }, op);
assert.ok(!taskResearchCurrent(updated, run), "changed briefs invalidate old research");
assert.notEqual(updated.taskPlan!.tasks.find(t => t.id === "research:brand")!.status, "done");
assert.equal(updated.runs.length, 1, "replanning retains history and usage");
const customer = projectView(updated, { ...op, role: "customer", identity: "firebase", accountId: "w" });
assert.equal(customer.taskPlan, undefined, "internal plans are not customer-visible");
assert.ok(customer.taskProgress?.length, "customer gets safe task progress");
assert.ok(!JSON.stringify(customer.taskProgress).includes("dependsOn"));
assert.deepEqual(planNext(v, true), { step: "scope" }, "planned orchestrator starts with its scope task");
registerResearchRunner(async () => {});
const readyResearch = make("Understand customer objections", "research");
readyResearch.scope = templateScope(readyResearch, { briefHash: "test", version: 1 });
readyResearch.reviews = [{ gate: "scope", subject: "v1" } as never];
assert.deepEqual(planNext(readyResearch, true), { step: "research" }, "orchestrator dispatches selected research tasks");
for (const segment of selectedResearch(readyResearch)) readyResearch.runs.push({ ...run, id: segment, segment, taskInputKey: readyResearch.taskPlan!.researchKey });
readyResearch.sources.push({ id: "s", segment: "brand", title: "Source", url: "https://example.com", excerpt: "Evidence", kind: "public_source", status: "supported", collectedAt: run.at, method: "test" });
readyResearch.insights.push({ id: "i", title: "Insight", interpretation: "Supported", sourceIds: ["s"], confidence: "limited", status: "reviewed", createdAt: run.at });
assert.equal((planNext(readyResearch, true) as { stop: { kind: string } }).stop.kind, "done", "research-only plans never enter production");
const heldResearch = structuredClone(readyResearch);
heldResearch.producerAgent = { hold: { gate: "sources", subject: "none", notes: "Evidence quality needs a human decision" } } as never;
syncTaskPlan(heldResearch);
assert.equal(heldResearch.taskPlan!.tasks.find(t => t.id === "reviewSources")!.status, "blocked", "holds take precedence over existing accepted items");
assert.throws(() => requirePlannedTask(heldResearch, "draftInsights"), /dependenc/i, "direct execution cannot bypass a source hold");
assert.equal((planNext(heldResearch, true) as { stop: { kind: string } }).stop.kind, "waiting_human");
const pendingResearch = structuredClone(readyResearch);
pendingResearch.producerAgent = { researchRetries: { brand: 1, customer: 1 }, pending: { gate: "insights", notes: "Rework interpretation" } } as never;
assert.deepEqual(planNext(pendingResearch, true), { step: "draftInsights" }, "research-only work must finish pending redrafts before completion");
const failedDraft = structuredClone(readyResearch);
failedDraft.insights = [];
failedDraft.runs.push({ ...run, id: "failed-draft", stage: "insights", segment: undefined, status: "failed", error: "Provider timed out; billing unknown", taskInputKey: failedDraft.taskPlan!.researchKey });
assert.equal((planNext(failedDraft, true) as { stop: { kind: string } }).stop.kind, "waiting_human", "failed paid drafting must never automatically retry");

let production = make("Create static advertising");
production.scope = templateScope(production, { briefHash: "test", version: 1 });
for (const segment of selectedResearch(production)) production.runs.push({ ...run, id: segment, segment, taskInputKey: production.taskPlan!.researchKey });
production.sources = structuredClone(readyResearch.sources);
production.insights = structuredClone(readyResearch.insights);
production = transition(production, { type: "selectFormats", formats: ["static"] }, op);
production.strategies.push({ id: "direction", version: 1, status: "approved", audience: "Customers", message: "Clear", rationale: "Evidence", design: "Calm", channels: "Email", format: "static", cta: "Read", evidenceIds: ["s"], insightIds: ["i"], hypothesis: "Test", uncertainties: "Unknown", createdAt: run.at, hash: "" });
production.strategies[0].hash = strategyHash(production.strategies[0]);
production = transition(production, { type: "produce" }, op);
assert.deepEqual(production.assets.map(a => a.kind), ["svg"], "static work never creates motion, a storyboard grid or copy");
assert.ok(production.taskPlan!.tasks.some(t => t.id === "production:svg" && t.status === "done"), "each selected production agent has its own task");
assert.ok(!production.taskPlan!.tasks.some(t => t.id === "draftCopyPack"), "static-only campaigns do not fire a copy pack agent");
const manualProject = structuredClone(production);
manualProject.formats!.selected = ["written_long"];
planProject(manualProject, op.subject, "Fixture for a producer's long-form deliverable");
assert.equal(manualProject.taskPlan!.tasks.find(t => t.id === "manual:written_long")!.status, "manual");
const finishedManual = transition(manualProject, { type: "completeManualTask", id: "manual:written_long", version: manualProject.taskPlan!.version, note: "Producer completed the long-form draft and recorded the handoff in the project." }, op);
assert.equal(finishedManual.taskPlan!.tasks.find(t => t.id === "manual:written_long")!.status, "done");
assert.throws(() => transition(production, { type: "completeManualTask", id: "assetApproval", version: production.taskPlan!.version, note: "Skip approval" }, op), /manual/i);
console.log("Customer task plans: relevance, dependencies, overrides, versioning, invalidation, isolation passed");
