import assert from 'node:assert/strict';
import { validatePerformance, performanceMetrics, performanceHistory, parsePerformanceCsv } from '../src/lib/factory/performance';
import { createProject, transition, projectView } from '../src/lib/factory/engine';
import { mediumEvidenceKey } from '../src/lib/factory/planning-context';
const op = { role: 'operator' as const, subject: 'producer', workspaceId: 'w' };
const input = { campaign: 'Launch', channel: 'instagram', format: 'static', objective: 'Purchases', audience: 'UK buyers', offer: 'Repairable product', start: '2026-10-01', end: '2026-10-31', provenance: 'Manually exported account report', attribution: '7-day click, reported not incremental', currency: 'GBP', impressions: 1000, clicks: 50, conversions: 5, spend: 100, revenue: 250, publicAuthorised: true };
const row = validatePerformance(input);
assert.equal(performanceMetrics(row).ctr, 0.05);
assert.equal(performanceMetrics(row).roas, 2.5);
assert.equal(performanceMetrics({...row, spend: 0}).roas, null);
assert.equal(performanceMetrics({...row, conversions: 0}).cpa, null);
assert.throws(() => validatePerformance({...input, clicks: -1}), /clicks/i);
assert.throws(() => validatePerformance({...input, clicks: 'bogus'}), /clicks/i);
assert.throws(() => validatePerformance({...input, end: '2026-09-01'}), /date|period/i);
assert.throws(() => validatePerformance({...input, provenance: ''}), /provenance/i);
assert.throws(() => validatePerformance({...input, conversions: 1.2}), /conversions/i);
let p = createProject({business:'Shop', objective:'Buy', contact:'x@y.com'}, op, 'p');
p = transition(p, {type:'recordPerformance', ...input}, op);
assert.equal(p.performance?.length,1);
assert.equal(performanceHistory(p).length,0);
const before = mediumEvidenceKey(p);
p = transition(p, {type:'reviewPerformance', id:p.performance![0].id, status:'accepted', revision:p.revision, reason:'Checked exported report'}, op);
assert.equal(performanceHistory(p).length,1);
assert.notEqual(mediumEvidenceKey(p),before);
assert.throws(() => transition(p,{type:'reviewPerformance',id:p.performance![0].id,status:'rejected',revision:0,reason:'Old view'},op), /changed|revision/i);
const customer = {role:'customer' as const,subject:'c',workspaceId:'w',projectId:'p'};
assert.equal(projectView(p,customer).performance,undefined);
assert.throws(() => transition(p,{type:'recordPerformance',...input},customer), /operator|producer/i);
const csv = 'campaign,channel,format,objective,audience,offer,start,end,provenance,attribution,currency,impressions,clicks,conversions,spend,revenue\n"Launch, one",instagram,static,Purchases,UK,Product,2026-10-01,2026-10-31,Export,7-day click,GBP,1000,50,5,100,250';
assert.equal(parsePerformanceCsv(csv)[0].campaign,'Launch, one');
assert.throws(()=>parsePerformanceCsv(csv+'\n"unterminated'), /csv|quote/i);
