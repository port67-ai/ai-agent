import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { LocalRepository } from '../src/lib/factory/repository';
import { reserveApiCall, finishApiCall, adminCostReport, reconcileApiCall, normalizeApiUsage, MAX_LEDGER_CALLS } from '../src/lib/factory/costs';
async function main() {
const repo = new LocalRepository(await mkdtemp(join(tmpdir(), 'cost-ledger-')));
process.env.PORT67_MODEL_PRICING_JSON = JSON.stringify({'test:model':{updatedAt:'2026-11-12',inputPerMillion:2,outputPerMillion:4,cachedInputPerMillion:1,toolPerCall:0.01}});
const input = { accountId:'a',workspaceId:'w',projectId:'p',runId:'r',stage:'research',provider:'test',model:'model',actor:'owner' };
const id = await reserveApiCall(repo,input);
let report = await adminCostReport(repo);
assert.equal(report.summary.unknownCount,1);
assert.equal(((await repo.read('w')) as {apiCalls?:unknown}).apiCalls,undefined);
await finishApiCall(repo,id,{status:'completed',usage:{inputTokens:1000,cachedInputTokens:400,outputTokens:100,toolCalls:1}});
report = await adminCostReport(repo);
assert.equal(report.summary.estimatedMicroUsd,12000);
assert.equal(report.summary.unknownCount,0);
assert.equal(report.rows[0].pricing?.updatedAt,'2026-11-12');
const unknown = await reserveApiCall(repo,{...input,model:'unpriced'});
await finishApiCall(repo,unknown,{status:'failed'});
assert.equal((await adminCostReport(repo)).summary.unknownCount,1);
await reconcileApiCall(repo,unknown,{actualMicroUsd:0,reference:'invoice-1',actor:'owner'});
report=await adminCostReport(repo,{limit:1});
assert.equal(report.total,2); assert.equal(report.rows.length,1);
assert.equal(report.summary.reconciledCount,1);
await assert.rejects(reconcileApiCall(repo,id,{actualMicroUsd:0.5,reference:'invoice',actor:'owner'}));

assert.equal((await adminCostReport(repo,{accountId:'other'})).total,0);
const blockedRepo = {read:repo.read.bind(repo),mutate:async()=>{throw new Error('storage unavailable');}};
await assert.rejects(reserveApiCall(blockedRepo,input),/storage unavailable/);
const fullRepo = new LocalRepository(await mkdtemp(join(tmpdir(), 'cost-full-')));
await fullRepo.mutate('factory-admin-ledger',db=>{(db as {apiCalls?:unknown[]}).apiCalls=Array.from({length:MAX_LEDGER_CALLS},()=>({}));});
await assert.rejects(reserveApiCall(fullRepo,input),/capacity/);
assert.equal((await adminCostReport(repo)).breakdown.model.length,2);
assert.equal(normalizeApiUsage({input_tokens:1}),undefined);
assert.equal(normalizeApiUsage({input_tokens:1.5,output_tokens:2}),undefined);
assert.deepEqual(normalizeApiUsage({input_tokens:100,output_tokens:20,cache_creation_input_tokens:30}),{inputTokens:100,outputTokens:20,cacheCreationInputTokens:30});
const malformed=await reserveApiCall(repo,{...input,actor:'a'.repeat(128),model:'m'.repeat(180)});
await finishApiCall(repo,malformed,{status:'failed',usage:{inputTokens:1,cachedInputTokens:2,outputTokens:0},providerRequestId:'req-1',rawUsage:{input_tokens:1,prompt:'secret',invalid:NaN}});
const malformedRow=(await adminCostReport(repo)).rows.find(r=>r.id===malformed)!;
assert.equal(malformedRow.status,'failed');assert.equal(malformedRow.estimatedMicroUsd,undefined);
assert.deepEqual(malformedRow.rawUsage,{input_tokens:1});assert.equal(malformedRow.providerRequestId,'req-1');
const cache=await reserveApiCall(repo,input);
await finishApiCall(repo,cache,{status:'completed',usage:{inputTokens:100,outputTokens:0,cacheCreationInputTokens:20}});
assert.equal((await adminCostReport(repo)).rows.find(r=>r.id===cache)!.estimatedMicroUsd,undefined);
process.env.PORT67_MODEL_PRICING_JSON=JSON.stringify({'test:model':{updatedAt:'2026-11-12',inputPerMillion:2,outputPerMillion:4,cacheCreationPerMillion:3}});
const cachePriced=await reserveApiCall(repo,input);
await finishApiCall(repo,cachePriced,{status:'completed',usage:{inputTokens:100,outputTokens:0,cacheCreationInputTokens:20}});
assert.equal((await adminCostReport(repo)).rows.find(r=>r.id===cachePriced)!.estimatedMicroUsd,220);
process.env.PORT67_MODEL_PRICING_JSON=JSON.stringify({'test:model':{updatedAt:'2026-02-31',inputPerMillion:2,outputPerMillion:4}});
await assert.rejects(reserveApiCall(repo,input),/version date/);
process.env.PORT67_MODEL_PRICING_JSON=JSON.stringify({'test:model':{updatedAt:'2026-11-12',inputPerMillion:2,outputPerMillion:4}});
const missingTools=await reserveApiCall(repo,input);
await finishApiCall(repo,missingTools,{status:'completed',usage:normalizeApiUsage({input_tokens:10,output_tokens:2,tool_usage_unknown:1})});
assert.equal((await adminCostReport(repo)).rows.find(r=>r.id===missingTools)!.estimatedMicroUsd,undefined);
console.log('Factory costs tests passed');

}
void main();
